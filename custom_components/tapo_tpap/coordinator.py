"""Polling and write calls. Does not perform write calls during polling."""
from __future__ import annotations

import logging
from typing import Any

from homeassistant.const import CONF_HOST, CONF_PASSWORD, CONF_USERNAME
from homeassistant.helpers.update_coordinator import DataUpdateCoordinator, UpdateFailed

from .const import DOMAIN, UPDATE_INTERVAL

_LOGGER = logging.getLogger(__name__)


class TapoCoordinator(DataUpdateCoordinator[dict[str, Any]]):
    """One device per config entry."""

    def __init__(self, hass, entry):
        super().__init__(hass, _LOGGER, name=f"{DOMAIN}_{entry.data[CONF_HOST]}",
                         update_interval=UPDATE_INTERVAL)
        self.entry = entry
        self.device = None

    async def _connect(self):
        # Private vendor namespace; never imports Home Assistant's shared kasa.
        # The vendored package is generated by the SHA-pinned HACS build.
        from ._vendor.kasa import Credentials, Discover
        device = await Discover.discover_single(
            self.entry.data[CONF_HOST],
            credentials=Credentials(
                self.entry.data[CONF_USERNAME],
                self.entry.data[CONF_PASSWORD],
            ),
        )
        if device is None:
            raise RuntimeError("Device discovery returned no device")
        self.device = device
        return device

    async def _async_update_data(self) -> dict[str, Any]:
        try:
            device = self.device or await self._connect()
            await device.update()
            features = {
                key: getattr(feat, "value", None)
                for key, feat in getattr(device, "features", {}).items()
            }
            return {
                "online": True,
                "is_on": bool(device.is_on),
                "model": str(device.model),
                "alias": str(device.alias),
                "features": features,
            }
        except Exception as exc:
            self.device = None
            raise UpdateFailed(f"Tapo read failed: {exc}") from exc

    async def async_set_relay(self, target: bool):
        """A real write occurs only via the switch control."""
        device = self.device or await self._connect()
        if target:
            await device.turn_on()
        else:
            await device.turn_off()
        await self.async_request_refresh()

    async def async_close(self):
        device = self.device
        self.device = None
        if device is not None and hasattr(device, "disconnect"):
            await device.disconnect()
